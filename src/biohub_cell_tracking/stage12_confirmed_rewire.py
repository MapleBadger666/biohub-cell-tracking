def _runtime_graph_state(graph):
    nodes = (
        graph.node_attrs(
            attr_keys=[
                "node_id",
                "t",
                "z",
                "y",
                "x",
            ]
        )
        .to_pandas()
        .set_index(
            "node_id"
        )
    )

    edges = (
        graph.edge_attrs(
            unpack=True
        )
        .to_pandas()
    )

    outdeg = (
        edges.groupby("source_id")
        .size()
        .astype(int)
        .to_dict()
    )

    indeg = (
        edges.groupby("target_id")
        .size()
        .astype(int)
        .to_dict()
    )

    edge_set = set(
        zip(
            edges[
                "source_id"
            ].astype(int),

            edges[
                "target_id"
            ].astype(int),
        )
    )

    return (
        nodes,

        {
            int(k): int(v)
            for k, v
            in outdeg.items()
        },

        {
            int(k): int(v)
            for k, v
            in indeg.items()
        },

        edge_set,
    )


