def apply_confirmed_rewire_policy(
    dataset,
    graph,
    *,
    pre_rewire_builder,
    artifact_dir,
):
    if dataset.startswith("44b6_"):
        return (
            graph,
            {
                "actions": 0,
                "source_incumbent_edges_removed": 0,
                "edges_added": 0,
                "net_edge_delta": 0,
            },
        )

    if not dataset.startswith("6bba_"):
        raise ValueError(
            f"Unsupported dataset prefix: {dataset}"
        )

    actions = build_confirmed_rewire_actions(
        dataset,
        pre_rewire_builder=pre_rewire_builder,
        artifact_dir=artifact_dir,
    )

    (
        nodes,
        outdeg,
        indeg,
        edge_set,
    ) = _runtime_graph_state(
        graph
    )

    edges = (
        graph.edge_attrs(
            unpack=True
        )
        .to_pandas()
        .copy()
    )

    edges["edge_id"] = edges["edge_id"].astype(int)
    edges["source_id"] = edges["source_id"].astype(int)
    edges["target_id"] = edges["target_id"].astype(int)

    outgoing = {}

    for src, sub in edges.groupby(
        "source_id"
    ):
        outgoing[int(src)] = [
            (
                int(row.edge_id),
                int(row.target_id),
            )
            for row
            in sub.itertuples(
                index=False
            )
        ]

    remove_ids = []
    add_rows = []

    for action in actions.itertuples(
        index=False
    ):
        src = int(action.source_id)
        tgt = int(action.target_id)

        if src == tgt:
            raise RuntimeError(
                "Self-edge in frozen action"
            )

        if (src, tgt) in edge_set:
            raise RuntimeError(
                "Frozen candidate already exists"
            )

        src_out = int(
            outdeg.get(
                src,
                0,
            )
        )

        tgt_in = int(
            indeg.get(
                tgt,
                0,
            )
        )

        # Frozen NO_TARGET_CUT.
        if tgt_in != 0:
            raise RuntimeError(
                (
                    "Target occupied under "
                    "NO_TARGET_CUT",
                    dataset,
                    src,
                    tgt,
                    tgt_in,
                )
            )

        if int(
            action.target_occupied
        ) != 0:
            raise RuntimeError(
                "Frozen action target_occupied != 0"
            )

        if src_out > 1:
            raise RuntimeError(
                (
                    "Unexpected source outdegree",
                    dataset,
                    src,
                    src_out,
                )
            )

        if int(
            action.source_occupied
        ) != int(
            src_out == 1
        ):
            raise RuntimeError(
                "source_occupied topology mismatch"
            )

        expected_cuts = int(
            src_out == 1
        )

        if int(
            action.cuts
        ) != expected_cuts:
            raise RuntimeError(
                "Frozen cuts topology mismatch"
            )

        if src_out == 1:
            src_edges = outgoing.get(
                src,
                [],
            )

            if len(src_edges) != 1:
                raise RuntimeError(
                    "Source incumbent cardinality mismatch"
                )

            remove_ids.append(
                int(
                    src_edges[0][0]
                )
            )

        dist = fv9.recovered_edge_dist(
            nodes,
            src,
            tgt,
            fv9.FROZEN_V9_CONFIG,
        )

        add_rows.append(
            (
                src,
                tgt,
                float(dist),
            )
        )

    if len(remove_ids) != len(
        set(remove_ids)
    ):
        raise RuntimeError(
            "Duplicate incumbent edge removals"
        )

    pre_edges = int(
        graph.num_edges()
    )

    if remove_ids:
        graph.bulk_remove_edges(
            sorted(remove_ids)
        )

    after_remove = int(
        graph.num_edges()
    )

    if (
        pre_edges
        -
        after_remove
    ) != len(remove_ids):
        raise RuntimeError(
            "Edge-removal count mismatch"
        )

    for src, tgt, dist in add_rows:
        if graph.has_edge(
            src,
            tgt,
        ):
            raise RuntimeError(
                "Candidate edge unexpectedly exists"
            )

        graph.add_edge(
            src,
            tgt,
            {
                "edge_dist":
                    float(dist),

                # Frozen evaluation representation contract.
                # Model score is NOT interpreted as calibrated
                # edge probability.
                "edge_prob":
                    1.0,
            },
            validate_keys=True,
        )

    post_edges = int(
        graph.num_edges()
    )

    if post_edges != (
        after_remove
        +
        len(add_rows)
    ):
        raise RuntimeError(
            "Post-mutation edge-count mismatch"
        )

    stats = {
        "actions":
            int(
                len(actions)
            ),

        "source_incumbent_edges_removed":
            int(
                len(remove_ids)
            ),

        "edges_added":
            int(
                len(add_rows)
            ),

        "net_edge_delta":
            int(
                post_edges
                -
                pre_edges
            ),
    }

    return graph, stats
