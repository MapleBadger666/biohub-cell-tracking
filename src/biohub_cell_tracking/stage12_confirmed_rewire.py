_MISSING = object()


def _generate_with_exact_pre_rewire_builder(
    dataset,
    pre_rewire_builder,
):
    global build_current_best

    previous = globals().get(
        "build_current_best",
        _MISSING,
    )

    globals()[
        "build_current_best"
    ] = pre_rewire_builder

    try:
        result = generate_dataset_proposals(
            dataset
        )

    finally:
        if previous is _MISSING:
            globals().pop(
                "build_current_best",
                None,
            )
        else:
            globals()[
                "build_current_best"
            ] = previous

    if not isinstance(result, tuple):
        raise RuntimeError(
            "Frozen proposal generator did not return tuple"
        )

    return result


