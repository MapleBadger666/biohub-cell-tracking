def policy_mask_g3h3(
    frame,
    a,
    b,
):

    sr = frame[
        "source_score_rank"
    ]


    tr = frame[
        "target_score_rank"
    ]


    return (
        (
            sr.le(
                a
            )
            &
            tr.le(
                b
            )
        )
        |
        (
            tr.le(
                a
            )
            &
            sr.le(
                b
            )
        )
    )


def resolve_conflicts_g3h3(
    frame,
):

    if len(
        frame
    ) == 0:

        return frame.copy()


    ordered = (
        frame
        .sort_values(
            [
                "model_score",
                "GMEAN_RATIO",
                "gap_size",
                "source_id",
                "target_id",
            ],
            ascending=[
                False,
                True,
                True,
                True,
                True,
            ],
            kind="stable",
        )
    )


    locked_nodes = set()

    accepted_index = []


    for row in ordered.itertuples():

        src = int(
            row.source_id
        )


        tgt = int(
            row.target_id
        )


        if src in locked_nodes:

            continue


        if tgt in locked_nodes:

            continue


        accepted_index.append(
            row.Index
        )


        locked_nodes.add(
            src
        )


        locked_nodes.add(
            tgt
        )


    return (
        frame.loc[
            accepted_index
        ]
        .copy()
    )


