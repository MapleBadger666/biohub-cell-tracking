def build_confirmed_rewire_actions(
    dataset,
    *,
    pre_rewire_builder,
    artifact_dir,
):
    result = _generate_with_exact_pre_rewire_builder(
        dataset,
        pre_rewire_builder,
    )

    proposals = result[0]

    proposals = add_endpoint_ranks(
        proposals
    )

    proposals = add_shortlist_rank_fields(
        proposals
    )

    shortlist = (
        proposals[
            frozen_shortlist_mask(
                proposals
            )
        ]
        .copy()
        .reset_index(
            drop=True
        )
    )

    shortlist = attach_scoring_features(
        shortlist
    )

    runtime = _load_frozen_runtime(
        str(
            Path(artifact_dir).resolve()
        )
    )

    shortlist[
        "model_score"
    ] = _score_frozen_full_dev(
        shortlist,
        runtime,
    )

    ranks = endpoint_score_ranks_g3h3(
        shortlist
    )

    shortlist[
        "source_score_rank"
    ] = ranks[
        "source_score_rank"
    ].to_numpy(
        copy=True
    )

    shortlist[
        "target_score_rank"
    ] = ranks[
        "target_score_rank"
    ].to_numpy(
        copy=True
    )

    rank_mask = policy_mask_g3h3(
        shortlist,
        a=1,
        b=5,
    )

    score_gated = shortlist[
        rank_mask
        &
        shortlist[
            "model_score"
        ].ge(
            DEPLOYMENT_THRESHOLD
        )
    ].copy()

    resolved = (
        resolve_conflicts_g3h3(
            score_gated
        )
        .copy()
        .reset_index(
            drop=True
        )
    )

    target_occupied = pd.to_numeric(
        resolved[
            "target_occupied"
        ],
        errors="raise",
    ).astype(
        int
    )

    selected = (
        resolved[
            target_occupied.eq(0)
        ]
        .copy()
        .reset_index(
            drop=True
        )
    )

    if not pd.to_numeric(
        selected[
            "target_occupied"
        ],
        errors="raise",
    ).astype(
        int
    ).eq(
        0
    ).all():
        raise RuntimeError(
            "NO_TARGET_CUT structural contract violated"
        )

    selected[
        "score_threshold"
    ] = DEPLOYMENT_THRESHOLD

    selected[
        "policy_id"
    ] = POLICY_ID

    return selected


